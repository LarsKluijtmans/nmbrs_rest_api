"""The ``Nmbrs`` facade: credentials in, resources out."""

from __future__ import annotations

import logging
from collections.abc import Callable, Iterable, Sequence
from datetime import datetime, timedelta, timezone
from typing import Any

import httpx

from nmbrs_rest._scopes import OFFLINE_ACCESS, REQUIRED_SCOPES
from nmbrs_rest.auth import AuthorizationRequest, OAuth
from nmbrs_rest.errors import (
    MultipleDebtorConsentsError,
    NmbrsConfigError,
    NotAuthenticatedError,
)
from nmbrs_rest.pagination import Page
from nmbrs_rest.resources.company import Company
from nmbrs_rest.resources.debtor import Debtor
from nmbrs_rest.resources.employee import Employee
from nmbrs_rest.tokens import CallbackTokenStore, MemoryTokenStore, Token
from nmbrs_rest.transport import DEFAULT_BASE_URL, Transport

logger = logging.getLogger(__name__)

TOKEN_KEY = "default"

#: Stand-in expiry for a token handed in without one: unambiguously spent.
EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)

COMPANIES = "/api/companies"
DEBTORS = "/api/debtors"

#: Every ``.read`` scope the API declares on a GET operation, plus ``offline_access``.
#: Convenient for one-off scripts; grant something narrower in a real integration.
ALL_READ_SCOPES: frozenset[str] = frozenset(
    scope
    for (method, _template), scopes in REQUIRED_SCOPES.items()
    if method == "GET"
    for scope in scopes
    if scope.endswith(".read")
) | {OFFLINE_ACCESS}

#: A small starter set: enough to list companies and read employee basics.
DEFAULT_SCOPES: tuple[str, ...] = (
    OFFLINE_ACCESS,
    "company.info.read",
    "employee.info.read",
    "employee.employment.read",
)


class Nmbrs:
    """Entry point for the Nmbrs REST API.

    The whole lifecycle lives here - credentials, consent, tokens, and the reads
    they unlock::

        api = Nmbrs(client_id, client_secret, subscription_key)

        url = api.login("https://yourapp.example/callback")   # send the user here
        api.authenticate(code)                                # code from the redirect

        api.access_token       # persist these
        api.refresh_token

        for company in api.companies():
            for employee in api.employees(company.id):
                employee.contracts()

    Coming back later skips the browser entirely::

        api = Nmbrs(client_id, client_secret, subscription_key, refresh_token=saved)

    **Refresh tokens rotate.** Nmbrs invalidates the old one every time it issues a
    new one, so a value you read once and stored goes stale as soon as the SDK
    refreshes in the background. ``access_token`` and ``refresh_token`` below are
    live properties, never snapshots - but if your app persists them, pass
    ``on_token_refresh`` so you are told the moment they change rather than having
    to poll.
    """

    def __init__(
        self,
        client_id: str,
        client_secret: str,
        subscription_key: str,
        *,
        access_token: str | None = None,
        refresh_token: str | None = None,
        expires_at: datetime | None = None,
        scopes: Iterable[str] | None = None,
        redirect_uri: str | None = None,
        on_token_refresh: Callable[[Token], None] | None = None,
        base_url: str = DEFAULT_BASE_URL,
        timeout: float = 30.0,
        max_retries: int = 3,
        http_client: httpx.Client | None = None,
        user_agent: str | None = None,
    ) -> None:
        if not subscription_key:
            raise NmbrsConfigError(
                "subscription_key is required. It is a separate credential from "
                "OAuth, generated by subscribing to a product at "
                "developer.nmbrs.com/products, and is sent as X-Subscription-Key."
            )

        self._oauth = OAuth(
            client_id=client_id,
            client_secret=client_secret,
            redirect_uri=redirect_uri,
            timeout=timeout,
        )
        self._subscription_key = subscription_key
        self._base_url = base_url
        self._timeout = timeout
        self._max_retries = max_retries
        self._http_client = http_client
        self._user_agent = user_agent
        self._on_token_refresh = on_token_refresh

        self._memory = MemoryTokenStore()
        self._store = CallbackTokenStore(
            load=self._memory.load,
            save=self._persist,
            delete=self._memory.delete,
        )

        self._transport: Transport | None = None
        self._pending: AuthorizationRequest | None = None
        self._pending_redirect_uri: str | None = None
        self._companies: dict[str, Company] = {}
        self._debtors: dict[str, Debtor] = {}

        if access_token or refresh_token:
            self._store.save(
                TOKEN_KEY,
                Token(
                    access_token=access_token or "",
                    refresh_token=refresh_token,
                    expires_at=expires_at or _assumed_expiry(refresh_token),
                    scopes=tuple(scopes or ()),
                ),
            )

    # -- token plumbing ----------------------------------------------------- #

    def _persist(self, key: str, token: Token) -> None:
        """Keep the in-process copy first, then tell the application.

        Order matters. The in-memory copy is what keeps *this* process working, so
        it is updated before anything that might fail. If the callback raises, the
        exception propagates - a silent failure to persist a rotated refresh token
        is how integrations die overnight - but the process itself stays usable.
        """
        self._memory.save(key, token)
        if self._on_token_refresh is not None:
            self._on_token_refresh(token)

    @property
    def token(self) -> Token | None:
        """The current token, or ``None`` before authentication."""
        return self._store.load(TOKEN_KEY)

    @property
    def authenticated(self) -> bool:
        return self.token is not None

    @property
    def access_token(self) -> str | None:
        """Live, not a snapshot: reflects the most recent refresh."""
        token = self.token
        return token.access_token if token else None

    @property
    def refresh_token(self) -> str | None:
        """Live, not a snapshot. Rotates on every refresh - persist it each time."""
        token = self.token
        return token.refresh_token if token else None

    @property
    def expires_at(self) -> datetime | None:
        token = self.token
        return token.expires_at if token else None

    @property
    def scopes(self) -> frozenset[str]:
        """Scopes actually granted, which may be narrower than those requested."""
        token = self.token
        return token.granted_scopes if token else frozenset()

    # -- the authorization code flow ---------------------------------------- #

    def login(
        self,
        redirect_uri: str | None = None,
        scopes: Sequence[str] | None = None,
        *,
        state: str | None = None,
        pkce: bool = False,
        par: bool = False,
    ) -> str:
        """Build the URL to send the end user to, and return it.

        ``state`` and any PKCE verifier are remembered on this object, so a script
        can call :meth:`authenticate` straight afterwards with nothing else. A web
        app cannot rely on that - the redirect usually lands on a different request
        or worker - so read :attr:`pending_login` and pass the values back in.

        Include ``offline_access`` in ``scopes`` or no refresh token is issued and
        the integration stops working in an hour. The default set does.
        """
        requested = tuple(scopes) if scopes is not None else DEFAULT_SCOPES
        request = self._oauth.authorization_url(
            requested, state=state, redirect_uri=redirect_uri, pkce=pkce, par=par
        )
        self._pending = request
        # RFC 6749 s4.1.3: the token exchange must present the *same* redirect_uri
        # as the authorization request, so remember it rather than making the
        # caller repeat it to authenticate().
        self._pending_redirect_uri = redirect_uri
        return request.url

    @property
    def pending_login(self) -> AuthorizationRequest | None:
        """The in-flight authorization request: its ``state`` and PKCE verifier."""
        return self._pending

    def authenticate(
        self,
        code: str,
        *,
        state: str | None = None,
        redirect_uri: str | None = None,
        code_verifier: str | None = None,
    ) -> Token:
        """Exchange the authorization code for tokens and start using them.

        The authorization code is single use and expires after five minutes.

        ``state`` is checked against the value issued by :meth:`login`; skipping
        that check is a real CSRF vulnerability, so it happens whenever the value
        is known. Pass ``state``/``code_verifier`` explicitly when the redirect is
        handled by a different process than the one that called :meth:`login`.
        """
        pending = self._pending
        token = self._oauth.exchange_code(
            code,
            redirect_uri=redirect_uri or self._pending_redirect_uri,
            code_verifier=code_verifier if code_verifier is not None else _verifier(pending),
            returned_state=state,
            expected_state=pending.state if pending is not None else None,
        )
        self._store.save(TOKEN_KEY, token)
        self._pending = None
        self._pending_redirect_uri = None
        self._transport = None  # rebuild against the new token
        return token

    def refresh(self) -> Token:
        """Force a refresh now, rather than waiting for expiry."""
        current = self.token
        if current is None or not current.refresh_token:
            raise NotAuthenticatedError(
                "cannot refresh: there is no refresh token. Authorize with the "
                "'offline_access' scope to receive one."
            )
        token = self._oauth.refresh(current.refresh_token)
        self._store.save(TOKEN_KEY, token)
        return token

    def logout(self) -> None:
        """Revoke the refresh token upstream and forget everything locally."""
        token = self.token
        if token is not None and token.refresh_token:
            self._oauth.revoke(token.refresh_token)
        self._store.delete(TOKEN_KEY)
        self._transport = None
        self._companies.clear()
        self._debtors.clear()

    # -- transport ---------------------------------------------------------- #

    @property
    def transport(self) -> Transport:
        """The underlying HTTP layer. Raises if there is no token yet."""
        if self.token is None:
            raise NotAuthenticatedError
        if self._transport is None:
            self._transport = Transport(
                subscription_key=self._subscription_key,
                oauth=self._oauth,
                token_store=self._store,
                token_key=TOKEN_KEY,
                base_url=self._base_url,
                timeout=self._timeout,
                max_retries=self._max_retries,
                http_client=self._http_client,
                user_agent=self._user_agent,
            )
        return self._transport

    # -- resources ---------------------------------------------------------- #

    def debtors(self) -> list[Debtor]:
        """``GET /api/debtors`` - every debtor this token can see."""
        found = [self._debtor(str(row.get("debtorId", "")), row) for row in self._all(DEBTORS)]
        return found

    def debtor(self, debtor_id: str) -> Debtor:
        return self._debtor(debtor_id, None)

    def companies(self) -> list[Company]:
        """Every company this token can see.

        Normally one request to ``GET /api/companies``. That endpoint refuses a token
        consented for more than one debtor (40306), so in that case the debtors are
        walked instead - same result, one request per debtor. Nothing to configure;
        the fallback only runs when the direct call is rejected.
        """
        try:
            rows = self._all(COMPANIES)
        except MultipleDebtorConsentsError:
            logger.debug("/api/companies refused multi-debtor consent; going via debtors")
            return self._companies_via_debtors()
        return [self._company(str(row.get("companyId", "")), row) for row in rows]

    def _companies_via_debtors(self) -> list[Company]:
        """Collect companies one debtor at a time, de-duplicated and registered."""
        found: list[Company] = []
        seen: set[str] = set()
        for debtor in self.debtors():
            for company in debtor.companies():
                if company.id in seen:
                    continue
                seen.add(company.id)
                # Re-register through the client so `api.company(id)` keeps returning
                # the same object, and its cache with it.
                found.append(self._company(company.id, company.raw))
        return found

    def company(self, company_id: str) -> Company:
        return self._company(company_id, None)

    def employees(self, company_id: str, **filters: Any) -> list[Employee]:
        """Every employee in a company. Shorthand for ``api.company(id).employees()``."""
        return self.company(company_id).employees(**filters)

    def employee(self, company_id: str, employee_id: str) -> Employee:
        """One employee, in one request.

        Both ids are required: Nmbrs exposes no employee-to-company lookup, and an
        employee id on its own is not enough to read anything but the bare record.
        """
        return self.company(company_id).employee(employee_id)

    # -- internals ---------------------------------------------------------- #

    def _all(self, template: str) -> list[dict[str, Any]]:
        return list(Page(self.transport, template, factory=lambda row: row))

    def _company(self, company_id: str, data: dict[str, Any] | None) -> Company:
        existing = self._companies.get(company_id)
        if existing is None:
            existing = Company(self.transport, company_id, data=data)
            self._companies[company_id] = existing
        elif data is not None and not existing._data:
            existing._data = data
        return existing

    def _debtor(self, debtor_id: str, data: dict[str, Any] | None) -> Debtor:
        existing = self._debtors.get(debtor_id)
        if existing is None:
            existing = Debtor(self.transport, debtor_id, data=data)
            self._debtors[debtor_id] = existing
        elif data is not None and not existing._data:
            existing._data = data
        return existing

    # -- lifecycle ---------------------------------------------------------- #

    def close(self) -> None:
        if self._transport is not None:
            self._transport.close()
        self._oauth.close()

    def __enter__(self) -> Nmbrs:
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    def __repr__(self) -> str:
        state = "authenticated" if self.authenticated else "not authenticated"
        return f"Nmbrs({state}, scopes={len(self.scopes)})"


def _verifier(request: AuthorizationRequest | None) -> str | None:
    return request.code_verifier if request is not None else None


def _assumed_expiry(refresh_token: str | None) -> datetime:
    """Expiry for a token handed in without one.

    With a refresh token, treat it as already spent: refreshing costs one request
    and is guaranteed correct, which beats discovering a 401 halfway through a job.

    Without one there is nothing to refresh *with*, so assuming it is dead would
    make a perfectly good access token unusable. Assume the documented one-hour
    lifetime instead and let a 401 speak for itself if that was wrong.
    """
    if refresh_token:
        return EPOCH
    return datetime.now(tz=timezone.utc) + timedelta(hours=1)
