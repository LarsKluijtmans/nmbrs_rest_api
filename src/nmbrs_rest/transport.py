"""HTTP transport: authentication, token refresh, retries, error mapping.

Everything that talks to ``api.nmbrsapp.com`` goes through here. Resource classes
never touch httpx directly.
"""

from __future__ import annotations

import logging
import random
import threading
import time
from typing import Any, Final

import httpx

from nmbrs_rest.auth import OAuth
from nmbrs_rest.errors import (
    APIError,
    InvalidGrantError,
    NmbrsConfigError,
    NmbrsConnectionError,
    NmbrsTimeoutError,
    Operation,
    QuotaExceededError,
    RateLimitError,
    ReauthorizationRequired,
    ServerError,
    exception_for,
)
from nmbrs_rest.tokens import MemoryTokenStore, Token, TokenStore

__all__ = ["DEFAULT_BASE_URL", "Transport"]

DEFAULT_BASE_URL: Final[str] = "https://api.nmbrsapp.com"

#: Statuses worth trying again. 500 is excluded: it is a real Nmbrs-side bug and
#: retrying rarely helps.
_RETRY_STATUSES: Final[frozenset[int]] = frozenset({429, 502, 503})

logger = logging.getLogger("nmbrs_rest")


class Transport:
    """Authenticated HTTP client for the Nmbrs REST API."""

    def __init__(
        self,
        *,
        subscription_key: str,
        token: Token | None = None,
        oauth: OAuth | None = None,
        token_store: TokenStore | None = None,
        token_key: str = "default",
        base_url: str = DEFAULT_BASE_URL,
        timeout: float = 30.0,
        max_retries: int = 3,
        max_rate_limit_retries: int = 5,
        http_client: httpx.Client | None = None,
        user_agent: str | None = None,
    ) -> None:
        if not subscription_key:
            raise NmbrsConfigError(
                "subscription_key is required. It is a separate credential from OAuth, "
                "generated by subscribing to a product at developer.nmbrs.com/products, "
                "and is sent as the X-Subscription-Key header on every request."
            )

        self.subscription_key = subscription_key
        self.oauth = oauth
        self.token_key = token_key
        self.base_url = base_url.rstrip("/")
        self.max_retries = max_retries
        self.max_rate_limit_retries = max_rate_limit_retries

        self.store: TokenStore = token_store or MemoryTokenStore()
        if token is not None:
            self.store.save(token_key, token)
        elif self.store.load(token_key) is None:
            raise NmbrsConfigError(
                "no token available: pass token=... or a token_store already holding "
                f"a token under key {token_key!r}."
            )

        from nmbrs_rest import __version__

        self._client = http_client or httpx.Client(timeout=timeout)
        self._owns_client = http_client is None
        self._user_agent = user_agent or f"nmbrs-rest-api/{__version__}"
        self._refresh_lock = threading.Lock()

    # -- lifecycle --------------------------------------------------------- #

    def close(self) -> None:
        if self._owns_client:
            self._client.close()

    def __enter__(self) -> Transport:
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    # -- tokens ------------------------------------------------------------ #

    @property
    def token(self) -> Token:
        token = self.store.load(self.token_key)
        if token is None:
            raise ReauthorizationRequired(
                "the token disappeared from the store", token_key=self.token_key
            )
        return token

    def _refresh(self, current: Token, *, force: bool = False) -> Token:
        """Refresh under a lock, persisting before returning.

        Nmbrs refresh tokens are single use, so two concurrent refreshes mean one
        of them gets ``invalid_grant``. The lock serialises in-process; the double
        check means waiters use the winner's token instead of refreshing again.

        ``force`` is for the reactive 401 path. There the server has rejected the
        access token even though our own clock says it is still valid - revoked
        consent, or clock skew - so an expiry check would wrongly short-circuit and
        the replay would reuse the token that was just refused. The double check
        then compares access tokens instead: a *different* one in the store means
        another worker already refreshed, so use theirs.
        """
        if self.oauth is None:
            raise ReauthorizationRequired(
                "the access token expired and no OAuth client was configured to refresh it",
                token_key=self.token_key,
            )

        with self._refresh_lock:
            latest = self.store.load(self.token_key) or current
            if force:
                if latest.access_token != current.access_token:
                    return latest  # someone else already refreshed
            elif not latest.is_expired():
                return latest  # someone else already refreshed

            if latest.refresh_token is None:
                raise ReauthorizationRequired(
                    "the access token expired and there is no refresh token "
                    "(was 'offline_access' requested at consent time?)",
                    token_key=self.token_key,
                )

            try:
                new = self.oauth.refresh(latest.refresh_token)
            except InvalidGrantError as exc:
                # Benign race or genuinely dead? A newer token in the store means
                # another worker rotated it between our load and our refresh.
                stored = self.store.load(self.token_key)
                if stored is not None and stored.refresh_token != latest.refresh_token:
                    logger.debug("refresh raced; using the token another worker stored")
                    return stored
                raise ReauthorizationRequired(
                    f"refresh token rejected ({exc.error}). It has expired, been used "
                    f"already, or the user revoked consent",
                    token_key=self.token_key,
                ) from exc

            # Persist BEFORE use. A crash after this point is recoverable; a crash
            # before it is not.
            self.store.save(self.token_key, new)
            logger.debug("refreshed access token for %r", self.token_key)
            return new

    def _ensure_fresh(self) -> Token:
        token = self.token
        return self._refresh(token) if token.is_expired() else token

    # -- requests ----------------------------------------------------------- #

    def _headers(self, token: Token) -> dict[str, str]:
        return {
            "Authorization": f"{token.token_type} {token.access_token}",
            "X-Subscription-Key": self.subscription_key,
            "Accept": "application/json",
            "User-Agent": self._user_agent,
        }

    @staticmethod
    def _retry_after(response: httpx.Response) -> float | None:
        """Read Retry-After if present.

        Nmbrs documents no rate-limit headers and none appear in the spec, so this
        is opportunistic rather than something to rely on.
        """
        raw = response.headers.get("Retry-After")
        if not raw:
            return None
        try:
            return max(0.0, float(raw))
        except ValueError:
            return None

    def _sleep_for(self, attempt: int, retry_after: float | None) -> float:
        if retry_after is not None:
            return retry_after
        # Exponential with full jitter. Without jitter a throttled fleet retries in
        # lockstep and throttles itself again.
        return random.uniform(0, min(2.0**attempt, 30.0))

    def request(
        self,
        method: str,
        template: str,
        *,
        path: str | None = None,
        params: dict[str, Any] | None = None,
        json: Any = None,
    ) -> httpx.Response:
        """Perform an authenticated request, retrying and refreshing as needed.

        ``template`` is the spec path (``/api/companies/{companyId}``) and is used
        for scope diagnosis; ``path`` is the concrete URL path actually requested.
        """
        target = path or template
        url = f"{self.base_url}{target}"
        clean = {k: v for k, v in (params or {}).items() if v is not None}

        refreshed_once = False
        attempt = 0
        rate_limit_attempts = 0

        while True:
            token = self._ensure_fresh()
            operation = Operation(
                method=method.upper(),
                template=template,
                path=target,
                granted_scopes=token.granted_scopes,
            )

            try:
                response = self._client.request(
                    method, url, params=clean, json=json, headers=self._headers(token)
                )
            except httpx.TimeoutException as exc:
                # A write that timed out may still have been applied upstream.
                if method.upper() != "GET" or attempt >= self.max_retries:
                    raise NmbrsTimeoutError(f"{operation} timed out: {exc}") from exc
                time.sleep(self._sleep_for(attempt, None))
                attempt += 1
                continue
            except httpx.HTTPError as exc:
                if method.upper() != "GET" or attempt >= self.max_retries:
                    raise NmbrsConnectionError(f"{operation} failed: {exc}") from exc
                time.sleep(self._sleep_for(attempt, None))
                attempt += 1
                continue

            if not response.is_error:
                return response

            # 401: refresh once and replay. Never loop - a second 401 after a good
            # refresh is a different problem, and retrying burns tokens.
            if response.status_code == 401 and not refreshed_once and self.oauth is not None:
                refreshed_once = True
                # force=True: the server rejected this token, so do not let a
                # not-yet-expired check skip the refresh.
                self._refresh(token, force=True)
                continue

            error = exception_for(
                status_code=response.status_code,
                body=response.content,
                content_type=response.headers.get("Content-Type"),
                operation=operation,
                request_id=response.headers.get("X-Request-Id"),
                retry_after=self._retry_after(response),
            )

            if self._should_retry(error, response.status_code, attempt, rate_limit_attempts):
                if isinstance(error, RateLimitError):
                    wait = self._sleep_for(rate_limit_attempts, error.retry_after)
                    rate_limit_attempts += 1
                else:
                    wait = self._sleep_for(attempt, None)
                    attempt += 1
                logger.debug("retrying %s after %.2fs (%s)", operation, wait, type(error).__name__)
                time.sleep(wait)
                continue

            raise error

    def _should_retry(
        self,
        error: APIError,
        status_code: int,
        attempt: int,
        rate_limit_attempts: int,
    ) -> bool:
        if status_code not in _RETRY_STATUSES:
            return False
        # Quota is exhausted for the billing period; waiting inside the process
        # cannot help.
        if isinstance(error, QuotaExceededError):
            return False
        if isinstance(error, RateLimitError):
            return rate_limit_attempts < self.max_rate_limit_retries
        if isinstance(error, ServerError):
            return attempt < self.max_retries
        return False

    # -- convenience --------------------------------------------------------- #

    def get_json(
        self,
        template: str,
        *,
        path: str | None = None,
        params: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        response = self.request("GET", template, path=path, params=params)
        try:
            payload = response.json()
        except ValueError as exc:
            raise APIError(
                http_status=response.status_code,
                detail=f"expected JSON but could not parse the response body: {exc}",
                operation=Operation(method="GET", template=template, path=path or template),
            ) from exc
        return payload if isinstance(payload, dict) else {"data": payload}
